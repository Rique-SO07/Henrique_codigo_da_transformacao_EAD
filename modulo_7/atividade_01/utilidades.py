# Nosso módulo para criar utilidades básicas


def somar(a, b):
    return a + b


"""Retorna a soma de dois números"""


def subtrair(a, b):
    return a - b


"""Retorna a subtração de dois números"""


def calcular_potencia(base, expoente):
    return base**expoente


"""Retorna base ** expoente"""
